#!/usr/bin/env python3
"""#2548 — decompose `certify_external`'s inner-KKT residual at a known state.

This is the evidence base for the issue as retitled ("one scalar tolerance for
two blocks of different extensivity"). It is fit-free and runs in seconds.

⚠ THE TRAP THIS SCRIPT EXISTS TO AVOID. I first tried to isolate the
non-reconstruction part of the residual by setting `X := 0`, and read the
resulting 525 as "a residual that is non-zero with no data". That is wrong:
setting the target to zero does NOT zero the reconstruction residual, it makes it
`-recon`. With a non-zero decoder the model still predicts `Phi(t) B`, so the
residual is large by construction and the probe isolates nothing. **An input set
to zero only zeroes the residual if the model predicts zero there.** The correct
isolation is the TRIVIAL state, `X = 0` and `B = 0`, which is the first row
below.

What the three rows establish:
  X=0, B=0          -> machine zero  ⇒ there is NO additive term at all: no prior
                       floor, no un-penalised constant, no frame offset.
  X=0, B=planted    -> large         ⇒ this is a residual, not a floor (see above).
  X=Phi@B, B=planted-> 332.779 @ n=400 ⇒ the quantity that needs explaining: a
                       non-zero certified gradient at a state whose reconstruction
                       residual is IDENTICALLY ZERO and whose penalties are e^-40.

and the two ladders establish its scaling: exactly first-order in the state
magnitude, and exactly extensive in the row count, against a bound that grows
like sqrt(n) by construction (`1e-5 * (1 + ||iterate||_2)`, whose per-row block
has n*(d+1)*K entries).

The data is generated by the library's OWN basis evaluator, so no convention gap
can be argued: `periodic_harmonic_basis` returns [1, cos t, sin t] in RADIANS and
agrees with a hand-written basis to max|delta| = 0.0.

OPEN, and NOT decided by this script: whether the 332.779 is (A) a legitimate
term of the quasi-Laplace criterion whose gradient is non-zero at the
least-squares optimum — in which case the certifier is right and the FIXTURE is
wrong — or (B) a state-proportional, row-extensive contribution that should not
be there. The discriminator is a finite-difference of the criterion the certifier
reports against its own reported gradient, which needs the criterion's VALUE
exposed alongside its gradient; `certify_external` does not currently return it.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

import numpy as np


def certify_raw(gamfit, X, t, B, *, lam=-40.0, identity_frame=True, **over):
    """`inner_kkt.raw_gradient_norm` for one installed external state."""
    n, p = X.shape
    kw = dict(
        geometry_plans=[{
            "kind": "periodic", "latent_dim": 1,
            "resolution": {"kind": "periodic_harmonics", "order": 1},
            "reference_metric": {"kind": "unit_circle"},
        }],
        decoder_blocks=[np.ascontiguousarray(B)],
        t_init=[np.ascontiguousarray(t.reshape(-1, 1))],
        a_init=np.zeros((n, 1)),
        log_lambda_smooth=[lam], log_ard=[[lam]], log_lambda_sparse=lam,
        assignment="softmax", n_iter=1,
    )
    if identity_frame:
        kw["tier0_mean"] = np.zeros(p)
        kw["tier0_scale"] = np.ones(p)
    kw.update(over)
    report = gamfit.sae.sae_manifold_certify_external(np.ascontiguousarray(X), **kw)
    inner = report.get("inner_kkt") or {}
    return inner.get("raw_gradient_norm"), inner.get("stationarity_bound")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--site", default=os.path.expanduser("~/f2_site"))
    ap.add_argument("--n", type=int, default=400)
    ap.add_argument("--p", type=int, default=16)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", default=None)
    args = ap.parse_args()

    sys.path.insert(0, args.site)
    import gamfit
    from gamfit._rust import periodic_harmonic_basis as PHB

    records = []

    def emit(rec):
        records.append(rec)
        if args.out:
            with open(args.out, "a") as fh:
                fh.write(json.dumps(rec, sort_keys=True, default=str) + "\n")

    rng = np.random.default_rng(args.seed)
    n, p = args.n, args.p
    t = rng.uniform(-np.pi, np.pi, n)
    phi = np.asarray(PHB(t, 1))
    B = rng.standard_normal((3, p)) / np.sqrt(p)

    hand = np.stack([np.ones(n), np.cos(t), np.sin(t)], axis=1)
    drift = float(np.abs(phi - hand).max())
    print(f"library basis vs hand-written [1, cos t, sin t]: max|delta| = {drift}")
    emit({"record": "basis_check", "max_abs_delta": drift})

    print(f"\nDECOMPOSITION (identity frame, penalties e^-40, "
          f"n={n} p={p} K=1)")
    for label, X, dec in (
        ("X=0,       B=0        (trivial state)", np.zeros((n, p)), np.zeros((3, p))),
        ("X=0,       B=planted  (resid = -recon)", np.zeros((n, p)), B),
        ("X=Phi@B,   B=planted  (resid == 0)", phi @ B, B),
    ):
        raw, bound = certify_raw(gamfit, X, t, dec)
        r2 = (1.0 - float(((X - phi @ dec) ** 2).sum())
              / max(float(((X - X.mean(0)) ** 2).sum()), 1e-300))
        print(f"  {label:38s} raw={raw!r:24s} bound={bound:.4g}")
        emit({"record": "decomposition", "arm": label.split("(")[0].strip(),
              "raw": raw, "bound": bound, "recon_r2": r2, "n": n, "p": p})

    print("\nJOINT SCALING of the exact state (residual stays 0 at every s)")
    for s in (1e-3, 1e-2, 1e-1, 1.0, 10.0, 100.0):
        raw, bound = certify_raw(gamfit, s * (phi @ B), t, s * B)
        print(f"  s={s:<8g} raw={raw!r}")
        emit({"record": "joint_scale", "scale": s, "raw": raw, "bound": bound})

    print("\nROW-COUNT LADDER, exact state at every n "
          "(raw/sqrt(n) doubling per 4x in n == raw proportional to n)")
    for nn in (100, 400, 1600, 6400):
        r2 = np.random.default_rng(7)
        tt = r2.uniform(-np.pi, np.pi, nn)
        XX = np.asarray(PHB(tt, 1)) @ B
        raw, bound = certify_raw(gamfit, XX, tt, B)
        print(f"  n={nn:<6d} raw={raw:<14.6g} bound={bound:<12.5g} "
              f"raw/sqrt(n)={raw / np.sqrt(nn):<10.4g} ratio={raw / bound:.4g}")
        emit({"record": "n_ladder", "n": nn, "raw": raw, "bound": bound,
              "raw_over_sqrt_n": raw / float(np.sqrt(nn)),
              "ratio": raw / bound})

    print("\nThe non-causes, each ruled out by a bit-identical or near-identical raw:")
    base, _ = certify_raw(gamfit, phi @ B, t, B)
    for label, over in (("alpha=0.25", {"alpha": 0.25}), ("alpha=4", {"alpha": 4.0}),
                        ("tau=0.1", {"tau": 0.1}), ("tau=0.9", {"tau": 0.9})):
        raw, _ = certify_raw(gamfit, phi @ B, t, B, **over)
        print(f"  {label:12s} raw={raw!r}  delta={raw - base:+.3e}")
        emit({"record": "non_cause", "knob": label, "raw": raw,
              "delta_from_base": raw - base})
    for la in (-40.0, -10.0, 0.0):
        raw, _ = certify_raw(gamfit, phi @ B, t, B, log_ard=[[la]])
        print(f"  log_ard={la:<6g} raw={raw!r}  delta={raw - base:+.3e}")
        emit({"record": "non_cause", "knob": f"log_ard={la}", "raw": raw,
              "delta_from_base": raw - base})

    print(f"\n{len(records)} records"
          + (f" written to {args.out}" if args.out else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
