/// A computed value with a derived bound on its roundoff.
#[derive(Clone, Debug)]
pub struct Evaluation {
    /// The computed value.
    pub value: Array1<f64>,
    /// Bound on `‖value − f(x)‖∞` over every exact input `x` within the
    /// evaluation's input roundoff of the supplied input.
    pub roundoff: f64,
}

/// A native computation between coordinate spaces: a transition, a readout, a
/// chart's encoder or decoder, or a descended map. It owns its error model.
pub trait NativeMap {
    /// Dimension of the input coordinates.
    fn input_dimension(&self) -> usize;
    /// Dimension of the output coordinates.
    fn output_dimension(&self) -> usize;
    /// The computed value at `input`, with a bound on its sup-norm distance to
    /// the exact map's value at every input within `input_roundoff` (sup norm)
    /// of `input`.
    fn evaluate(
        &self,
        input: ArrayView1<'_, f64>,
        input_roundoff: f64,
    ) -> Result<Evaluation, StateError>;
}

/// An analytic Jacobian with a bound on its formation error.
#[derive(Clone, Debug)]
pub struct JacobianEvaluation {
    /// `output_dimension × input_dimension`.
    pub matrix: Array2<f64>,
    /// Bound on the spectral norm of `matrix` minus the exact Jacobian at the
    /// supplied input.
    pub roundoff: f64,
}

/// A native map with an analytic Jacobian.
pub trait DifferentiableNativeMap: NativeMap {
    /// The Jacobian at `input`.
    fn jacobian(&self, input: ArrayView1<'_, f64>) -> Result<JacobianEvaluation, StateError>;
}

/// What a state-check verdict ranges over, as an evidence-status domain.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum StateDomain {
    /// The stated native states, by row.
    States { count: usize },
    /// The stated codes, by row.
    Codes { count: usize },
    /// The tested states of a fibre test times its futures. Vacuous states lay on
    /// the section and are not in the family.
    FiberPairs {
        tested_states: usize,
        vacuous_states: usize,
        futures: usize,
    },
    /// Every state of `ℝᵈ` through a spectral norm, so a bound scales with the
    /// state's norm.
    UnitStates { dimension: usize },
}

/// A stated native state, by row: the witness of a quotient-contract verdict.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct StateRow(pub usize);

/// A stated code, by row: the witness of a realization-contract verdict.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct CodeRow(pub usize);

/// A fibre-test witness: a stated state, its section representative, the future
/// compared on them, and the resolution at which the chart merges the pair.
#[derive(Clone, Debug, PartialEq)]
pub struct FiberWitness {
    pub state: usize,
    pub future: usize,
    pub representative: Array1<f64>,
    pub merge_bound: f64,
}

/// The quotient contract `E'∘T = g∘E`: the code of the transitioned state is the
/// descended code.
pub struct QuotientContract<'a> {
    /// `T : H → H'`.
    pub transition: &'a dyn NativeMap,
    /// `E : H → Z`.
    pub encoder: &'a dyn NativeMap,
    /// `E' : H' → Z'`.
    pub next_encoder: &'a dyn NativeMap,
    /// `g : Z → Z'`.
    pub descended: &'a dyn NativeMap,
}

/// What [`QuotientContract::check`] resolved over the stated states.
#[derive(Clone, Debug, PartialEq)]
pub enum QuotientContractVerdict {
    /// At `state`, `‖E'(T h) − g(E h)‖∞ = defect` exceeds the combined roundoff
    /// of both sides: the code does not descend. This is the state with the
    /// largest excess.
    Violated {
        state: usize,
        defect: f64,
        roundoff: f64,
    },
    /// At every stated state the exact defect is at most `bound`, roundoff
    /// included. `roundoff` is the largest combined roundoff, kept for audit, and
    /// `states` counts the stated states.
    Bounded {
        bound: f64,
        roundoff: f64,
        states: usize,
    },
}

impl QuotientContractVerdict {
    /// The verdict as the evidence status of `sup_h ‖E'(T h) − g(E h)‖∞` over the
    /// stated states.
    pub fn evidence(&self) -> Result<EvidenceStatus<StateRow, StateDomain>, EvidenceStatusError> {
        match *self {
            Self::Violated {
                state,
                defect,
                roundoff,
            } => EvidenceStatus::counterexample(defect, roundoff, 0.0, StateRow(state)),
            Self::Bounded {
                bound,
                roundoff,
                states,
            } => EvidenceStatus::uniform_bound(bound, roundoff, StateDomain::States { count: states }),
        }
    }
}

impl QuotientContract<'_> {
    /// Check the contract at native states, the rows of `states`.
    pub fn check(
        &self,
        states: ArrayView2<'_, f64>,
    ) -> Result<QuotientContractVerdict, StateError> {
        let dimension = self.transition.input_dimension();
        require_dimension(
            self.encoder.input_dimension(),
            dimension,
            "quotient contract: E and T share a state space",
        )?;
        require_dimension(
            self.next_encoder.input_dimension(),
            self.transition.output_dimension(),
            "quotient contract: T into E'",
        )?;
        require_dimension(
            self.descended.input_dimension(),
            self.encoder.output_dimension(),
            "quotient contract: E into g",
        )?;
        require_dimension(
            self.descended.output_dimension(),
            self.next_encoder.output_dimension(),
            "quotient contract: E' and g share a code space",
        )?;
        require_sample(states, dimension, "quotient contract: states")?;
        let mut record = DefectRecord::new();
        for (index, state) in states.rows().into_iter().enumerate() {
            let moved = evaluated(self.transition, state, 0.0, "quotient contract: T(h)")?;
            let after = evaluated(
                self.next_encoder,
                moved.value.view(),
                moved.roundoff,
                "quotient contract: E'(T h)",
            )?;
            let code = evaluated(self.encoder, state, 0.0, "quotient contract: E(h)")?;
            let descended = evaluated(
                self.descended,
                code.value.view(),
                code.roundoff,
                "quotient contract: g(E h)",
            )?;
            record.observe(
                index,
                sup_distance(after.value.view(), descended.value.view()),
                after.roundoff + descended.roundoff,
            )?;
        }
        Ok(match record.violation {
            Some((state, defect, roundoff, _)) => QuotientContractVerdict::Violated {
                state,
                defect,
                roundoff,
            },
            None => QuotientContractVerdict::Bounded {
                bound: record.bound,
                roundoff: record.roundoff,
                states: record.count,
            },
        })
    }
}

/// The realization contract `T∘D = D'∘g`: decoded representatives are carried
/// to decoded representatives.
pub struct RealizationContract<'a> {
    /// `T : H → H'`.
    pub transition: &'a dyn NativeMap,
    /// `D : Z → H`.
    pub decoder: &'a dyn NativeMap,
    /// `D' : Z' → H'`.
    pub next_decoder: &'a dyn NativeMap,
    /// `g : Z → Z'`.
    pub descended: &'a dyn NativeMap,
}

/// What [`RealizationContract::check`] resolved over the stated codes.
#[derive(Clone, Debug, PartialEq)]
pub enum RealizationContractVerdict {
    /// At `code`, `‖T(D z) − D'(g z)‖∞ = defect` exceeds the combined roundoff
    /// of both sides: the decoded representative is not carried to the decoded
    /// representative. This is the code with the largest excess.
    Violated {
        code: usize,
        defect: f64,
        roundoff: f64,
    },
    /// At every stated code the exact defect is at most `bound`, roundoff
    /// included. `roundoff` is the largest combined roundoff, kept for audit, and
    /// `codes` counts the stated codes.
    Bounded {
        bound: f64,
        roundoff: f64,
        codes: usize,
    },
}

impl RealizationContractVerdict {
    /// The verdict as the evidence status of `sup_z ‖T(D z) − D'(g z)‖∞` over the
    /// stated codes.
    pub fn evidence(&self) -> Result<EvidenceStatus<CodeRow, StateDomain>, EvidenceStatusError> {
        match *self {
            Self::Violated {
                code,
                defect,
                roundoff,
            } => EvidenceStatus::counterexample(defect, roundoff, 0.0, CodeRow(code)),
            Self::Bounded {
                bound,
                roundoff,
                codes,
            } => EvidenceStatus::uniform_bound(bound, roundoff, StateDomain::Codes { count: codes }),
        }
    }
}

impl RealizationContract<'_> {
    /// Check the contract at codes, the rows of `codes`.
    pub fn check(
        &self,
        codes: ArrayView2<'_, f64>,
    ) -> Result<RealizationContractVerdict, StateError> {
        let dimension = self.decoder.input_dimension();
        require_dimension(
            self.descended.input_dimension(),
            dimension,
            "realization contract: D and g share a code space",
        )?;
        require_dimension(
            self.transition.input_dimension(),
            self.decoder.output_dimension(),
            "realization contract: D into T",
        )?;
        require_dimension(
            self.next_decoder.input_dimension(),
            self.descended.output_dimension(),
            "realization contract: g into D'",
        )?;
        require_dimension(
            self.next_decoder.output_dimension(),
            self.transition.output_dimension(),
            "realization contract: T and D' share a state space",
        )?;
        require_sample(codes, dimension, "realization contract: codes")?;
        let mut record = DefectRecord::new();
        for (index, code) in codes.rows().into_iter().enumerate() {
            let decoded = evaluated(self.decoder, code, 0.0, "realization contract: D(z)")?;
            let moved = evaluated(
                self.transition,
                decoded.value.view(),
                decoded.roundoff,
                "realization contract: T(D z)",
            )?;
            let descended = evaluated(self.descended, code, 0.0, "realization contract: g(z)")?;
            let represented = evaluated(
                self.next_decoder,
                descended.value.view(),
                descended.roundoff,
                "realization contract: D'(g z)",
            )?;
            record.observe(
                index,
                sup_distance(moved.value.view(), represented.value.view()),
                moved.roundoff + represented.roundoff,
            )?;
        }
        Ok(match record.violation {
            Some((code, defect, roundoff, _)) => RealizationContractVerdict::Violated {
                code,
                defect,
                roundoff,
            },
            None => RealizationContractVerdict::Bounded {
                bound: record.bound,
                roundoff: record.roundoff,
                codes: record.count,
            },
        })
    }
}

/// A candidate sufficient state: an encoder together with a section of it.
pub struct StateChart<'a> {
    /// `E : H → Z`.
    pub encoder: &'a dyn NativeMap,
    /// `D : Z → H` with `E∘D = id` on the codes the encoder produces.
    pub decoder: &'a dyn NativeMap,
}

/// What [`fiber_test`] resolved over the stated states and futures.
#[derive(Clone, Debug, PartialEq)]
pub enum FiberVerdict {
    /// The chart maps `witness.state` and its section representative within
    /// `witness.merge_bound` of each other in code space, yet `witness.future`
    /// separates them by `distance`, and `distance − roundoff` exceeds the
    /// declared `fidelity`. This refutes the chart as a sufficient state at
    /// resolution `merge_bound`: no readout descended through the chart with a
    /// modulus of continuity `ω` satisfying `ω(merge_bound) < distance − roundoff`
    /// reproduces the future. In particular no readout Lipschitz below
    /// `(distance − roundoff) / merge_bound` does. Exact non-sufficiency needs an
    /// exact merge. This is the pair with the largest certified separation.
    Separated {
        witness: FiberWitness,
        distance: f64,
        roundoff: f64,
        fidelity: f64,
    },
    /// At every tested state every future agrees with its value at the
    /// representative within `separation_upper_bound`, roundoff included, and
    /// that bound is within the declared fidelity. `vacuous_states` lay on the
    /// section and tested nothing. `roundoff` is the largest combined roundoff,
    /// kept for audit.
    WithinFidelity {
        tested_states: usize,
        vacuous_states: usize,
        futures: usize,
        separation_upper_bound: f64,
        roundoff: f64,
    },
    /// No separation is certified above the declared fidelity, but the largest
    /// separation's roundoff interval contains it. `witness` attains
    /// `separation_lower_bound`.
    Unresolved {
        tested_states: usize,
        vacuous_states: usize,
        futures: usize,
        separation_lower_bound: f64,
        separation_upper_bound: f64,
        witness: FiberWitness,
    },
}

impl FiberVerdict {
    /// The verdict as the evidence status of `sup ‖r_k(h) − r_k(D(E h))‖∞` over
    /// the tested states and futures.
    pub fn evidence(
        &self,
    ) -> Result<EvidenceStatus<FiberWitness, StateDomain>, EvidenceStatusError> {
        match self {
            Self::Separated {
                witness,
                distance,
                roundoff,
                fidelity,
            } => EvidenceStatus::counterexample(*distance, *roundoff, *fidelity, witness.clone()),
            Self::WithinFidelity {
                tested_states,
                vacuous_states,
                futures,
                separation_upper_bound,
                roundoff,
            } => EvidenceStatus::uniform_bound(
                *separation_upper_bound,
                *roundoff,
                StateDomain::FiberPairs {
                    tested_states: *tested_states,
                    vacuous_states: *vacuous_states,
                    futures: *futures,
                },
            ),
            Self::Unresolved {
                tested_states,
                vacuous_states,
                futures,
                separation_lower_bound,
                separation_upper_bound,
                witness,
            } => EvidenceStatus::unresolved(
                *separation_lower_bound,
                *separation_upper_bound,
                Extremum::Supremum,
                Some(witness.clone()),
                StateDomain::FiberPairs {
                    tested_states: *tested_states,
                    vacuous_states: *vacuous_states,
                    futures: *futures,
                },
            ),
        }
    }
}

/// Test whether `chart` is a sufficient state for `futures` at the stated native
/// states, the rows of `states`.
///
/// Each state `h` is compared with its section representative `h̃ = D(E(h))`,
/// which the chart cannot tell apart from `h`, on every future. `fidelity` is
/// the declared largest sup-norm response difference that counts as agreement.
///
/// Refusals:
/// * [`StateError::NotASection`] when `E(D(E h))` differs from `E(h)` by more
///   than the arithmetic explains. Then `h̃` is not in the fibre of `h`, so a
///   separation would say nothing about `E`.
/// * [`StateError::VacuousFiberTest`] when every state lies on the section
///   within the decoder's roundoff, so every comparison is of a state with
///   itself.
pub fn fiber_test(
    chart: &StateChart<'_>,
    futures: &[&dyn NativeMap],
    states: ArrayView2<'_, f64>,
    fidelity: f64,
) -> Result<FiberVerdict, StateError> {
    if !fidelity.is_finite() || fidelity < 0.0 {
        return Err(StateError::InvalidFidelity { value: fidelity });
    }
    let dimension = chart.encoder.input_dimension();
    require_dimension(
        chart.decoder.input_dimension(),
        chart.encoder.output_dimension(),
        "fiber test: encoder into decoder",
    )?;
    require_dimension(
        chart.decoder.output_dimension(),
        dimension,
        "fiber test: decoder into the state space",
    )?;
    if futures.is_empty() {
        return Err(StateError::EmptyFamily {
            context: "fiber test: futures",
        });
    }
    for future in futures {
        require_dimension(
            future.input_dimension(),
            dimension,
            "fiber test: future on the state space",
        )?;
    }
    require_sample(states, dimension, "fiber test: states")?;
    let mut tested_states = 0;
    let mut vacuous_states = 0;
    let mut largest_upper = 0.0_f64;
    let mut largest_roundoff = 0.0_f64;
    // The pair whose evaluated separation has the largest certified lower bound:
    // if it does not refute the fidelity, no pair does.
    let mut strongest: Option<(FiberWitness, f64, f64, EvidenceStatus<(), ()>)> = None;
    for (index, state) in states.rows().into_iter().enumerate() {
        let code = evaluated(chart.encoder, state, 0.0, "fiber test: E(h)")?;
        let representative =
            evaluated(chart.decoder, code.value.view(), 0.0, "fiber test: D(E h)")?;
        let round_trip = evaluated(
            chart.encoder,
            representative.value.view(),
            representative.roundoff,
            "fiber test: E(D(E h))",
        )?;
        let code_defect = sup_distance(round_trip.value.view(), code.value.view());
        if code_defect > round_trip.roundoff {
            return Err(StateError::NotASection {
                state: index,
                code_defect,
                roundoff: round_trip.roundoff,
            });
        }
        if sup_distance(state, representative.value.view()) <= representative.roundoff {
            vacuous_states += 1;
            continue;
        }
        tested_states += 1;
        let merge_bound = code.roundoff + code_defect + round_trip.roundoff;
        for (future_index, future) in futures.iter().enumerate() {
            let native = evaluated(*future, state, 0.0, "fiber test: r(h)")?;
            let represented = evaluated(
                *future,
                representative.value.view(),
                0.0,
                "fiber test: r(D(E h))",
            )?;
            let distance = sup_distance(native.value.view(), represented.value.view());
            let roundoff = native.roundoff + represented.roundoff;
            let separation = evaluated_defect(distance, roundoff)?;
            largest_upper = largest_upper.max(certified_upper(&separation));
            largest_roundoff = largest_roundoff.max(roundoff);
            let larger = match &strongest {
                Some((_, _, _, best)) => certified_lower(&separation) > certified_lower(best),
                None => true,
            };
            if larger {
                strongest = Some((
                    FiberWitness {
                        state: index,
                        future: future_index,
                        representative: representative.value.clone(),
                        merge_bound,
                    },
                    distance,
                    roundoff,
                    separation,
                ));
            }
        }
    }
    let (witness, distance, roundoff, separation) = match strongest {
        Some(strongest) => strongest,
        None => {
            return Err(StateError::VacuousFiberTest {
                states: vacuous_states,
            });
        }
    };
    let futures = futures.len();
    Ok(if separation.refutes_at_most(fidelity) {
        FiberVerdict::Separated {
            witness,
            distance,
            roundoff,
            fidelity,
        }
    } else if largest_upper <= fidelity {
        FiberVerdict::WithinFidelity {
            tested_states,
            vacuous_states,
            futures,
            separation_upper_bound: largest_upper,
            roundoff: largest_roundoff,
        }
    } else {
        FiberVerdict::Unresolved {
            tested_states,
            vacuous_states,
            futures,
            separation_lower_bound: certified_lower(&separation).max(0.0),
            separation_upper_bound: largest_upper,
            witness,
        }
    })
}

/// The local quotient at one state, read off the stacked response Jacobian.
#[derive(Clone, Debug)]
pub struct LocalQuotient {
    /// Singular values of the stacked Jacobian, descending.
    pub singular_values: Vec<f64>,
    /// The SVD's backward-error band plus the stacked Jacobians' formation
    /// bound.
    pub band: f64,
    /// Number of singular values above `band`: a certified lower bound on the
    /// exact rank at the state.
    pub resolved_rank: usize,
    /// `min(response rows, d)`, the most the rank can be.
    pub rank_ceiling: usize,
    /// Orthonormal rows (`resolved_rank × d`) spanning the state directions the
    /// futures resolve. To first order their orthogonal complement is tangent to
    /// the fibre.
    pub observed_directions: Array2<f64>,
}

/// The local dimension a state's resolved rank supports.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum LocalDimension {
    /// The resolved rank reaches its ceiling, so the rank is exact at the state.
    /// By lower semicontinuity it is constant on a neighbourhood. For a
    /// generating family this is the local minimal dimension.
    Certified(usize),
    /// The resolved rank equals the sample's generic rank but is below its
    /// ceiling. The exact rank is at least this; a larger one hidden below the
    /// band is not excluded.
    AtLeast(usize),
    /// The rank at this state is not resolved up to the sample's generic rank at
    /// this band: `largest_unresolved_singular_value ≤ band`. Either the exact
    /// rank drops here, or a singular value sits below the band. The check cannot
    /// tell which, so this is not a certificate of a singular point. Where the
    /// exact rank does drop and the response map is analytic on a connected
    /// domain, the generic rank is attained arbitrarily close, so the rank is not
    /// constant near the state and no constant-rank chart exists there. A merely
    /// smooth map can keep a lower rank on an open set.
    BelowGeneric {
        resolved_rank: usize,
        generic_rank: usize,
        largest_unresolved_singular_value: f64,
        band: f64,
    },
}

/// The resolved ranks of a response family over stated states.
#[derive(Clone, Debug)]
pub struct ConstantRankCheck {
    /// One local quotient per stated state, in row order.
    pub states: Vec<LocalQuotient>,
    /// The largest resolved rank over the stated states: a certified lower
    /// bound on the family's largest rank on them.
    pub generic_rank: usize,
}

impl ConstantRankCheck {
    /// The local dimension at stated state `state`, relative to the sample's
    /// generic rank.
    pub fn local_dimension(&self, state: usize) -> Option<LocalDimension> {
        self.states.get(state).map(|local| {
            if local.resolved_rank < self.generic_rank {
                LocalDimension::BelowGeneric {
                    resolved_rank: local.resolved_rank,
                    generic_rank: self.generic_rank,
                    largest_unresolved_singular_value: local
                        .singular_values
                        .get(local.resolved_rank)
                        .copied()
                        .unwrap_or(0.0),
                    band: local.band,
                }
            } else if local.resolved_rank == local.rank_ceiling {
                LocalDimension::Certified(local.resolved_rank)
            } else {
                LocalDimension::AtLeast(local.resolved_rank)
            }
        })
    }

    /// The exact rank of the stacked Jacobian at stated state `state`. At its
    /// ceiling the certified lower bound (Weyl) collapses onto the ceiling, so the
    /// rank is fixed by that identity and reported as [`ExactBasis::Algebraic`].
    /// Otherwise only the resolved lower bound and the ceiling are derived.
    pub fn rank_evidence(
        &self,
        state: usize,
    ) -> Option<Result<EvidenceStatus<StateRow, StateDomain>, EvidenceStatusError>> {
        self.states.get(state).map(|local| {
            if local.resolved_rank == local.rank_ceiling {
                EvidenceStatus::exact(
                    local.resolved_rank as f64,
                    0.0,
                    ExactBasis::Algebraic,
                    Some(StateRow(state)),
                    StateDomain::States { count: 1 },
                )
            } else {
                EvidenceStatus::unresolved(
                    local.resolved_rank as f64,
                    local.rank_ceiling as f64,
                    Extremum::Supremum,
                    None,
                    StateDomain::States { count: 1 },
                )
            }
        })
    }
}

/// Resolve the rank of the stacked Jacobian of `futures` at each stated state,
/// the rows of `states`.
///
/// This is the rank of the family as stated. It is the local minimal dimension
/// of the permitted family only if the stated futures generate it, and only at
/// states where [`LocalDimension::Certified`] holds. The check forms the stacked
/// `response rows × d` Jacobian of each state and its thin SVD.
pub fn constant_rank_check(
    governor: &MemoryGovernor,
    futures: &[&dyn DifferentiableNativeMap],
    states: ArrayView2<'_, f64>,
) -> Result<ConstantRankCheck, StateError> {
    let first = futures.first().ok_or(StateError::EmptyFamily {
        context: "constant rank: futures",
    })?;
    let dimension = first.input_dimension();
    for future in futures {
        require_dimension(
            future.input_dimension(),
            dimension,
            "constant rank: future on the state space",
        )?;
    }
    require_sample(states, dimension, "constant rank: states")?;
    let rows: usize = futures.iter().map(|future| future.output_dimension()).sum();
    if rows == 0 {
        return Err(StateError::EmptyFamily {
            context: "constant rank: responses",
        });
    }
    // One stacked Jacobian lives at a time: each state's replaces the last.
    let stacked_reservation = reserve(governor, rows, dimension, 1, "constant rank: stacked Jacobian")?;
    let mut locals = Vec::with_capacity(states.nrows());
    for state in states.rows() {
        let mut stacked = Array2::<f64>::zeros((rows, dimension));
        let mut formation_squared = 0.0_f64;
        let mut offset = 0;
        for future in futures {
            let jacobian = future.jacobian(state)?;
            let height = future.output_dimension();
            if jacobian.matrix.dim() != (height, dimension) {
                return Err(StateError::DimensionMismatch {
                    context: "constant rank: Jacobian shape",
                    expected: height * dimension,
                    found: jacobian.matrix.len(),
                });
            }
            if !jacobian.roundoff.is_finite()
                || jacobian.roundoff < 0.0
                || jacobian.matrix.iter().any(|value| !value.is_finite())
            {
                return Err(StateError::NonFinite {
                    context: "constant rank: Jacobian",
                });
            }
            stacked
                .slice_mut(s![offset..offset + height, ..])
                .assign(&jacobian.matrix);
            formation_squared += jacobian.roundoff * jacobian.roundoff;
            offset += height;
        }
        // The spectral norm of a stacked error is at most the root sum of the
        // blocks' squared spectral norms.
        locals.push(resolve_stacked_factor(governor, &stacked, formation_squared.sqrt())?);
    }
    drop(stacked_reservation);
    let generic_rank = locals
        .iter()
        .map(|local| local.resolved_rank)
        .max()
        .unwrap_or(0);
    Ok(ConstantRankCheck {
        states: locals,
        generic_rank,
    })
}

/// Resolve the rank and observed directions of a stacked factor whose exact value
/// lies within `formation` of `stacked` in spectral norm. A Frobenius bound on the
/// entrywise error is valid. The band is [`factor_singular_band`] plus
/// `formation`. [`constant_rank_check`] reads this resolver for stacked response
/// Jacobians. A caller whose factor is not the Jacobian of one native map, such as
/// a metric's weighted factor, calls it directly, so [`LocalQuotient`] has one
/// owner.
pub fn resolve_stacked_factor(
    governor: &MemoryGovernor,
    stacked: &Array2<f64>,
    formation: f64,
) -> Result<LocalQuotient, StateError> {
    let (rows, cols) = stacked.dim();
    if rows == 0 || cols == 0 {
        return Err(StateError::EmptyFamily {
            context: "stacked factor",
        });
    }
    if !formation.is_finite() || stacked.iter().any(|value| !value.is_finite()) {
        return Err(StateError::NonFinite {
            context: "stacked factor",
        });
    }
    if formation < 0.0 {
        return Err(StateError::NegativeBound {
            context: "stacked factor: formation",
            value: formation,
        });
    }
    let resolution = resolved_row_space(governor, stacked, formation, "stacked factor")?;
    Ok(LocalQuotient {
        singular_values: resolution.singular_values,
        band: resolution.band,
        resolved_rank: resolution.rank,
        rank_ceiling: rows.min(cols),
        observed_directions: resolution.rows,
    })
}

/// Bounds on the spectral norm of an exact matrix, read off its computed value.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct SpectralNormBounds {
    /// `max(0, σ̂₁ − band)`. A positive value certifies a nonzero exact matrix.
    pub lower: f64,
    /// `σ̂₁ + band`. The exact norm is at most this.
    pub upper: f64,
}

impl SpectralNormBounds {
    /// The bounds as the evidence status of `sup_{‖h‖₂ = 1} ‖R h‖₂` for the
    /// measured residual `R` on `ℝᵈ`.
    pub fn evidence(
        &self,
        dimension: usize,
    ) -> Result<EvidenceStatus<Array1<f64>, StateDomain>, EvidenceStatusError> {
        EvidenceStatus::unresolved(
            self.lower,
            self.upper,
            Extremum::Supremum,
            None,
            StateDomain::UnitStates { dimension },
        )
    }
}

/// A linear sufficient state `E(h) = Q h` for linear readouts `M_k` under linear
/// transitions `T_a`, with its descended maps and measured contract bounds.
///
/// Every bound holds at every state for the supplied matrices, scaled by the
/// state's norm:
/// * `‖M_k h − Ψ_k Q h‖ ≤ readout_bounds[k].upper · ‖h‖₂` with `Ψ_k = M_k Qᵀ`:
///   each readout is a function of the chart.
/// * `‖Q T_a h − G_a Q h‖ ≤ quotient_bounds[a].upper · ‖h‖₂` with
///   `G_a = Q T_a Qᵀ`: the quotient contract `E∘T_a = G_a∘E`.
/// * `‖T_a Qᵀ z − Qᵀ G_a z‖ ≤ realization_bounds[a].upper · ‖z‖₂`: the
///   realization contract for the decoder `D = Qᵀ`, which is a section of `Q`
///   to within `section_bounds`.
#[derive(Clone, Debug)]
pub struct LinearStateQuotient {
    /// `Q`, `r × d`.
    pub chart: Array2<f64>,
    /// `Ψ_k = M_k Qᵀ`, `p_k × r`.
    pub readout_maps: Vec<Array2<f64>>,
    /// `G_a = Q T_a Qᵀ`, `r × r`.
    pub descended: Vec<Array2<f64>>,
    /// `‖M_k − Ψ_k Q‖₂`.
    pub readout_bounds: Vec<SpectralNormBounds>,
    /// `‖Q T_a − G_a Q‖₂`.
    pub quotient_bounds: Vec<SpectralNormBounds>,
    /// `‖T_a Qᵀ − Qᵀ G_a‖₂`.
    pub realization_bounds: Vec<SpectralNormBounds>,
    /// `‖Q Qᵀ − I_r‖₂`.
    pub section_bounds: SpectralNormBounds,
}

impl LinearStateQuotient {
    /// The row span of the readouts closed under the transitions (the observable
    /// subspace), measured.
    ///
    /// Starting from the resolved row span of the stacked readouts, each step
    /// appends the chart's rows moved by every transition and resolves the stack
    /// again. The resolved dimension grows at every step that does not stop and
    /// cannot exceed `d`, so the closure ends without an iteration cap. A rank the
    /// band misjudges is not hidden: it surfaces in the measured quotient bounds.
    /// The number of chart rows is not a certified dimension, because each step's
    /// band leaves out the angle error of the previous step's singular vectors.
    /// The measured bounds are the certificate.
    pub fn close(
        governor: &MemoryGovernor,
        readouts: &[ArrayView2<'_, f64>],
        transitions: &[ArrayView2<'_, f64>],
    ) -> Result<Self, StateError> {
        let dimension = linear_family_dimension(readouts, transitions)?;
        let rows: usize = readouts.iter().map(|readout| readout.nrows()).sum();
        let stacked_reservation = reserve(governor, rows, dimension, 1, "linear quotient: readout rows")?;
        let mut stacked = Array2::<f64>::zeros((rows, dimension));
        let mut offset = 0;
        for readout in readouts {
            stacked
                .slice_mut(s![offset..offset + readout.nrows(), ..])
                .assign(readout);
            offset += readout.nrows();
        }
        let mut chart = resolved_row_space(governor, &stacked, 0.0, "linear quotient: readout rows")?.rows;
        drop(stacked);
        drop(stacked_reservation);
        loop {
            let rank = chart.nrows();
            if rank == 0 || rank == dimension || transitions.is_empty() {
                break;
            }
            // The candidate stack and the chart's absolute value and one moved copy.
            let candidate_reservation = reserve(
                governor,
                rank,
                dimension,
                transitions.len().saturating_add(3),
                "linear quotient: closure step",
            )?;
            let mut candidate =
                Array2::<f64>::zeros(((transitions.len() + 1) * rank, dimension));
            candidate.slice_mut(s![..rank, ..]).assign(&chart);
            let absolute_chart = chart.mapv(f64::abs);
            let mut formation_squared = 0.0_f64;
            for (index, transition) in transitions.iter().enumerate() {
                let start = (index + 1) * rank;
                candidate
                    .slice_mut(s![start..start + rank, ..])
                    .assign(&chart.dot(transition));
                formation_squared += absolute_chart
                    .dot(&transition.mapv(f64::abs))
                    .iter()
                    .map(|&magnitude| accumulation_band(dimension, magnitude).powi(2))
                    .sum::<f64>();
            }
            let next = resolved_row_space(
                governor,
                &candidate,
                formation_squared.sqrt(),
                "linear quotient: closure step",
            )?;
            drop(candidate);
            drop(candidate_reservation);
            if next.rank <= rank {
                break;
            }
            chart = next.rows;
        }
        Self::measure(governor, chart, readouts, transitions)
    }

    /// Measure a declared chart `Q` (`r × d`) against the readouts and
    /// transitions.
    pub fn measure(
        governor: &MemoryGovernor,
        chart: Array2<f64>,
        readouts: &[ArrayView2<'_, f64>],
        transitions: &[ArrayView2<'_, f64>],
    ) -> Result<Self, StateError> {
        let dimension = linear_family_dimension(readouts, transitions)?;
        require_dimension(chart.ncols(), dimension, "linear quotient: chart columns")?;
        if chart.iter().any(|value| !value.is_finite()) {
            return Err(StateError::NonFinite {
                context: "linear quotient: chart",
            });
        }
        let rank = chart.nrows();
        // `|Q|` and every `r × r` and `r × d` temporary one measurement holds at once.
        let working = reserve(governor, rank.max(1), dimension, 8, "linear quotient: measurement")?;
        let section = chart.t();
        let absolute_chart = chart.mapv(f64::abs);
        let absolute_section = absolute_chart.t();

        let section_residual = &chart.dot(&section) - &Array2::<f64>::eye(rank);
        let section_band = entrywise_band_norm(
            absolute_chart
                .dot(&absolute_section)
                .mapv(|magnitude| accumulation_band(dimension + 1, magnitude + 1.0)),
        );
        let section_bounds =
            spectral_norm_bounds(governor, &section_residual, section_band, "linear quotient: section")?;

        let mut readout_maps = Vec::with_capacity(readouts.len());
        let mut readout_bounds = Vec::with_capacity(readouts.len());
        for readout in readouts {
            let map = readout.dot(&section);
            let residual = readout - &map.dot(&chart);
            let band = entrywise_band_norm(
                map.mapv(f64::abs)
                    .dot(&absolute_chart)
                    .mapv(|magnitude| accumulation_band(rank + 1, magnitude))
                    + &readout.mapv(|entry| accumulation_growth(1) * entry.abs()),
            );
            readout_bounds.push(spectral_norm_bounds(
                governor,
                &residual,
                band,
                "linear quotient: readout",
            )?);
            readout_maps.push(map);
        }

        let mut descended = Vec::with_capacity(transitions.len());
        let mut quotient_bounds = Vec::with_capacity(transitions.len());
        let mut realization_bounds = Vec::with_capacity(transitions.len());
        for transition in transitions {
            let transition_reservation =
                reserve(governor, dimension, dimension, 1, "linear quotient: absolute transition")?;
            let absolute_transition = transition.mapv(f64::abs);
            let moved = chart.dot(transition);
            let map = moved.dot(&section);
            let absolute_map = map.mapv(f64::abs);
            let quotient_residual = &moved - &map.dot(&chart);
            let quotient_band = entrywise_band_norm(
                absolute_chart
                    .dot(&absolute_transition)
                    .mapv(|magnitude| accumulation_band(dimension + 1, magnitude))
                    + &absolute_map
                        .dot(&absolute_chart)
                        .mapv(|magnitude| accumulation_band(rank + 1, magnitude)),
            );
            quotient_bounds.push(spectral_norm_bounds(
                governor,
                &quotient_residual,
                quotient_band,
                "linear quotient: quotient contract",
            )?);
            let realization_residual = &transition.dot(&section) - &section.dot(&map);
            let realization_band = entrywise_band_norm(
                absolute_transition
                    .dot(&absolute_section)
                    .mapv(|magnitude| accumulation_band(dimension + 1, magnitude))
                    + &absolute_section
                        .dot(&absolute_map)
                        .mapv(|magnitude| accumulation_band(rank + 1, magnitude)),
            );
            realization_bounds.push(spectral_norm_bounds(
                governor,
                &realization_residual,
                realization_band,
                "linear quotient: realization contract",
            )?);
            descended.push(map);
            drop(transition_reservation);
        }
        drop(working);
        Ok(Self {
            chart,
            readout_maps,
            descended,
            readout_bounds,
            quotient_bounds,
            realization_bounds,
            section_bounds,
        })
    }
}

/// One forward step of a weighted observability pull-back ([`WeightedObservability`]).
///
/// The step maps the state `h_l ∈ ℝ^{n_l}` to `h_{l+1} ∈ ℝ^{n_{l+1}}` by one of
/// its declared letters, and its readouts read `h_{l+1}`.
#[derive(Clone, Debug)]
pub struct ObservabilityStep<'a> {
    /// The declared letters `T_{l,1..H}`, each `n_{l+1} × n_l`. The alphabet is
    /// exactly what is declared: a residual stream is the identity letter, passed
    /// like any other. An attention block enters only as
    /// [`ObservabilityLetter::RoutingLaws`], whose letters the joint-operator owner
    /// derives.
    pub letters: Vec<ObservabilityLetter<'a>>,
    /// Readouts `R_l` of `h_{l+1}`, each `p × n_{l+1}`. May be empty.
    pub readouts: Vec<ArrayView2<'a, f64>>,
}

/// Letters of an [`ObservabilityStep`].
#[derive(Clone, Debug)]
pub enum ObservabilityLetter<'a> {
    /// One linear letter `T`, `n_{l+1} × n_l`.
    Linear(ArrayView2<'a, f64>),
    /// The rank-one letters `C_j = u_j a_jᵀ` of the units of an MLP normal form
    /// `F(x) = Ax + b + Σ_j u_j ψ(a_jᵀx + β_j)`, one letter per unit: `reads`
    /// holds `a_j` as rows (`n × n_l`), `writes` holds `u_j` as rows
    /// (`n × n_{l+1}`). Pulled back together, `S C_j` has the Gramian of the one
    /// row `‖S u_j‖ a_jᵀ`, so an MLP step is `[Linear(A), Units{..}]` and adds
    /// `Aᵀ G A + Σ_j (u_jᵀ G u_j) a_j a_jᵀ`: each read weighted by how strongly
    /// its write is read. The units must be the merged normal form
    /// (`module_split::MlpNormalForm`): a pair of units with opposite affine forms
    /// is one term of the function, and left unmerged its cancelling writes
    /// each add energy that the function does not carry.
    Units {
        reads: ArrayView2<'a, f64>,
        writes: ArrayView2<'a, f64>,
    },
    /// An attention block's letters, one per routing law: the summed value/output
    /// transport of the heads that share one attention pattern, derived by
    /// `joint_operators::attention_letters` from the block's own query/key operators,
    /// the only constructor of [`RoutingLawLetters`]. One letter per head is not
    /// invariant under the cross-head `GL` gauge of heads with one pattern (it moves
    /// each head's transport and not their sum), and it over-counts, so it cannot be
    /// declared here. Each transport carries its formation band, which the pull-back
    /// propagates as `‖S‖_F ‖E‖_F`.
    RoutingLaws(&'a RoutingLawLetters),
}

impl ObservabilityLetter<'_> {
    /// `(n_{l+1}, n_l)`.
    fn shape(&self) -> (usize, usize) {
        match self {
            Self::Linear(letter) => letter.dim(),
            Self::Units { reads, writes } => (writes.ncols(), reads.ncols()),
            Self::RoutingLaws(letters) => letters.transports().first().map_or((0, 0), |transport| transport.dim()),
        }
    }

    /// How many words of length one the letter stands for.
    fn count(&self) -> usize {
        match self {
            Self::Linear(_) => 1,
            Self::Units { reads, .. } => reads.nrows(),
            Self::RoutingLaws(letters) => letters.transports().len(),
        }
    }

    fn validate(&self, output: usize, input: usize) -> Result<(), StateError> {
        let context = "weighted observability: letter";
        require_dimension(self.shape().0, output, context)?;
        require_dimension(self.shape().1, input, context)?;
        match self {
            Self::Linear(letter) => require_finite(letter.view(), context),
            Self::Units { reads, writes } => {
                require_dimension(writes.nrows(), reads.nrows(), "weighted observability: units")?;
                require_finite(reads.view(), context)?;
                require_finite(writes.view(), context)
            }
            Self::RoutingLaws(letters) => {
                for transport in letters.transports() {
                    require_dimension(transport.nrows(), output, context)?;
                    require_dimension(transport.ncols(), input, context)?;
                    require_finite(transport.view(), context)?;
                }
                Ok(())
            }
        }
    }

    /// The pulled-back rows `S T` (or `‖S u_j‖ a_jᵀ`) and a Frobenius bound on
    /// their distance from those of the exact source, given the source's own
    /// bound `formation`.
    fn pull(&self, source: &Array2<f64>, absolute_source: &Array2<f64>, formation: f64) -> (Array2<f64>, f64) {
        let width = source.ncols();
        match self {
            Self::Linear(letter) => {
                let moved = source.dot(letter);
                let product_band = entrywise_band_norm(
                    absolute_source
                        .dot(&letter.mapv(f64::abs))
                        .mapv(|magnitude| accumulation_band(width, magnitude)),
                );
                (moved, formation * frobenius(letter) + product_band)
            }
            Self::Units { reads, writes } => {
                let read = source.dot(&writes.t());
                let read_band = absolute_source
                    .dot(&writes.t().mapv(f64::abs))
                    .mapv(|magnitude| accumulation_band(width, magnitude));
                let rows = source.nrows();
                let mut moved = reads.to_owned();
                let mut squared = 0.0_f64;
                for (unit, mut row) in moved.rows_mut().into_iter().enumerate() {
                    let weight = read.column(unit).iter().map(|value| value * value).sum::<f64>().sqrt();
                    let write_norm = writes.row(unit).iter().map(|value| value * value).sum::<f64>().sqrt();
                    let read_norm = row.iter().map(|value| value * value).sum::<f64>().sqrt();
                    let weight_error = formation * write_norm
                        + read_band.column(unit).iter().map(|value| value * value).sum::<f64>().sqrt()
                        + accumulation_growth(rows + 1) * weight;
                    row.mapv_inplace(|value| value * weight);
                    squared += ((weight_error + accumulation_growth(1) * weight) * read_norm).powi(2);
                }
                (moved, squared.sqrt())
            }
            Self::RoutingLaws(letters) => {
                let rows = source.nrows();
                let mut moved = Array2::<f64>::zeros((rows * letters.transports().len(), width));
                let mut squared = 0.0_f64;
                let source_norm = frobenius(source);
                for (index, (transport, &band)) in letters.transports().iter().zip(letters.bands()).enumerate() {
                    moved.slice_mut(s![index * rows..(index + 1) * rows, ..]).assign(&source.dot(transport));
                    let product_band = entrywise_band_norm(
                        absolute_source
                            .dot(&transport.mapv(f64::abs))
                            .mapv(|magnitude| accumulation_band(width, magnitude)),
                    );
                    let error = formation * (frobenius(transport) + band) + product_band + source_norm * band;
                    squared += error * error;
                }
                (moved, squared.sqrt() * (1.0 + accumulation_growth(2 * letters.transports().len() + 1)))
            }
        }
    }
}

/// The spectrum of an observability Gramian `G = Fᵀ F`, read off its factor `F`.
#[derive(Clone, Debug)]
pub struct ObservabilitySpectrum {
    /// `σ₁ ≥ σ₂ ≥ …` of `F`, so the eigenvalues of `G` are `σᵢ²`. The Gramian
    /// itself is never formed.
    pub singular_values: Vec<f64>,
    /// Every `σᵢ` is within this of a singular value of a factor of the exact
    /// Gramian: [`factor_singular_band`] plus the pull-back's formation bound.
    pub band: f64,
    /// Singular values above `band`: a certified lower bound on the exact rank.
    pub resolved_rank: usize,
    /// `min(stacked rows, n)`: the exact rank cannot exceed it.
    pub rank_ceiling: usize,
    /// `tr G = Σ σᵢ²`.
    pub energy: f64,
    /// `(Σ σᵢ²)² / Σ σᵢ⁴`, the effective number of directions under the
    /// Gramian's own weighting. A summary of the spectrum with no cutoff; zero
    /// for a zero Gramian.
    pub participation_ratio: f64,
}

impl ObservabilitySpectrum {
    /// The exact rank of the Gramian: exact at its ceiling, otherwise the
    /// resolved lower bound and the ceiling.
    pub fn rank_evidence(&self) -> Result<EvidenceStatus<(), StateDomain>, EvidenceStatusError> {
        let domain = StateDomain::UnitStates {
            dimension: self.rank_ceiling,
        };
        if self.resolved_rank == self.rank_ceiling {
            EvidenceStatus::exact(
                self.resolved_rank as f64,
                0.0,
                ExactBasis::Algebraic,
                None,
                domain,
            )
        } else {
            EvidenceStatus::unresolved(
                self.resolved_rank as f64,
                self.rank_ceiling as f64,
                Extremum::Supremum,
                None,
                domain,
            )
        }
    }

    fn of(singular_values: Vec<f64>, rows: usize, cols: usize, formation: f64, stacked_rows: usize) -> Self {
        let sigma_max = singular_values.first().copied().unwrap_or(0.0);
        let band = factor_singular_band(rows.max(1), cols, sigma_max) + formation;
        let resolved_rank = singular_values.iter().filter(|&&value| value > band).count();
        let energy: f64 = singular_values.iter().map(|value| value * value).sum();
        let quartic: f64 = singular_values.iter().map(|value| value.powi(4)).sum();
        let participation_ratio = if quartic > 0.0 { energy * energy / quartic } else { 0.0 };
        Self {
            singular_values,
            band,
            resolved_rank,
            rank_ceiling: stacked_rows.min(cols),
            energy,
            participation_ratio,
        }
    }
}

/// The weighted observability Gramian of a readout family pulled back through
/// declared forward steps, held as a factor.
///
/// # Definition
///
/// Steps `l = 0..L−1` run forward, `h_{l+1} = T_{l,a} h_l` for a letter `a` of
/// step `l`, and step `l`'s readouts `R_l` read `h_{l+1}`. A word
/// `w = (a_0, …, a_l)` picks one letter per step up to `l`, with
/// `T_w = T_{l,a_l} ⋯ T_{0,a_0}`. The Gramian at the input `h_0` is
///
/// ```text
/// G = Σ_{l=0}^{L−1} Σ_{w = (a_0..a_l)} (R_l T_w)ᵀ (R_l T_w)        (n_0 × n_0),
/// ```
///
/// every readout pulled back along every declared word with unit weight. It is
/// the per-step stacked factor of the operation-first probes: from the last step
/// backward, `S = [F_{l+1}; R_l]` and `F_l = [S T_{l,1}; …; S T_{l,H}]`, so
/// `F_lᵀ F_l = Σ_a T_{l,a}ᵀ (F_{l+1}ᵀ F_{l+1} + Σ R_lᵀ R_l) T_{l,a}` and
/// `G = F_0ᵀ F_0`. A time-invariant family pulled back to depth `k` is one step
/// repeated `k` times. The range of `G` lies in the exact observable subspace
/// that [`LinearStateQuotient::close`] computes for the same readouts and
/// letters; what the weighting adds is how strongly each direction is read.
/// Exact rank questions are generically saturated on trained weights, so the
/// spectrum, not the rank, carries the information.
///
/// After every letter the stack is compressed to `diag(σ) Vᵀ` by a thin SVD,
/// which keeps `Fᵀ F`, so `G` is never formed and memory is `O(n²)` per letter.
///
/// # Error
///
/// `formation` bounds the Frobenius distance from `factor` to a factor of the
/// exact Gramian of the supplied matrices, up to a left orthogonal factor. Each
/// product `S T` adds the propagated bound times `‖T‖_F` and the
/// [`accumulation_band`] of `|S||T|`; each compression adds the SVD's backward
/// error ([`factor_singular_band`], times `√rank` for Frobenius), `σ₁` times the
/// measured orthogonality defect of `V`, and the rounding of `σᵢ Vᵢⱼ`.
#[derive(Clone, Debug)]
pub struct WeightedObservability {
    /// `F = diag(σ) Vᵀ` at `h_0`, `min(rows, n_0) × n_0`, with `Fᵀ F = G`.
    pub factor: Array2<f64>,
    /// `V`'s rows: the Gramian's eigenvectors in decreasing `σ`.
    pub directions: Array2<f64>,
    /// Frobenius bound on the distance of `factor` from an exact factor.
    pub formation: f64,
    /// `step_spectra[l]` is the spectrum at `h_l`, the input of step `l`, of the
    /// pull-back of steps `l..L`. `step_spectra[0]` is the spectrum of `G`.
    pub step_spectra: Vec<ObservabilitySpectrum>,
}

/// How much of the weighted observability a declared candidate subspace holds.
#[derive(Clone, Debug)]
pub struct SubspaceCapture {
    /// The candidate's dimension `k`.
    pub dimension: usize,
    /// `tr(Π G) / tr G = ‖F Wᵀ‖²_F / ‖F‖²_F` for the orthogonal projector
    /// `Π = Wᵀ W` onto the candidate, with its numerical error. A uniformly
    /// random `k`-dimensional subspace captures `k/n` in expectation.
    pub energy_fraction: EvidenceStatus<(), StateDomain>,
    /// Cosines of the principal angles between the top `min(k, rows)` Gramian
    /// directions and the candidate, in decreasing order.
    pub principal_cosines: Vec<f64>,
    /// `σ_k² − σ_{k+1}²`, the eigengap that separates the top `k` directions
    /// (`σ_{k+1} = 0` past the factor's rows).
    pub eigengap: f64,
    /// A Davis–Kahan bound on the sine of the largest angle between the computed
    /// and the exact top-`k` space: `‖ΔG‖₂ / (gap − ‖ΔG‖₂)` with
    /// `‖ΔG‖₂ ≤ 2σ₁e + e²`, `e` the factor's error, capped at `1`, and `1` when
    /// the gap does not exceed `‖ΔG‖₂`.
    pub angle_perturbation: f64,
}

impl WeightedObservability {
    /// Pull the readouts of `steps`, in forward order, back to `h_0`.
    pub fn pull_back(governor: &MemoryGovernor, steps: &[ObservabilityStep<'_>]) -> Result<Self, StateError> {
        let last = steps.last().ok_or(StateError::EmptyFamily {
            context: "weighted observability: steps",
        })?;
        if steps.iter().all(|step| step.readouts.is_empty()) {
            return Err(StateError::EmptyFamily {
                context: "weighted observability: readouts",
            });
        }
        let mut width = last
            .letters
            .first()
            .ok_or(StateError::EmptyFamily {
                context: "weighted observability: letters",
            })?
            .shape()
            .0;
        let mut factor = Array2::<f64>::zeros((0, width));
        let mut directions = Array2::<f64>::zeros((0, width));
        let mut formation = 0.0_f64;
        let mut stacked_rows = 0_usize;
        let mut step_spectra = Vec::with_capacity(steps.len());
        for step in steps.iter().rev() {
            let input = step
                .letters
                .first()
                .ok_or(StateError::EmptyFamily {
                    context: "weighted observability: letters",
                })?
                .shape()
                .1;
            for letter in &step.letters {
                letter.validate(width, input)?;
            }
            for readout in &step.readouts {
                require_sample(readout.view(), width, "weighted observability: readout")?;
            }
            let readout_rows: usize = step.readouts.iter().map(|readout| readout.nrows()).sum();
            let source_rows = factor.nrows() + readout_rows;
            // The source stack and its absolute value.
            let source_reservation =
                reserve(governor, source_rows.max(1), width, 2, "weighted observability: step source")?;
            let mut source = Array2::<f64>::zeros((source_rows, width));
            source.slice_mut(s![..factor.nrows(), ..]).assign(&factor);
            let mut offset = factor.nrows();
            for readout in &step.readouts {
                source
                    .slice_mut(s![offset..offset + readout.nrows(), ..])
                    .assign(readout);
                offset += readout.nrows();
            }
            let absolute_source = source.mapv(f64::abs);
            let mut pulled = Array2::<f64>::zeros((0, input));
            let mut pulled_directions = Array2::<f64>::zeros((0, input));
            let mut pulled_sigma = Vec::new();
            let mut pulled_formation = 0.0_f64;
            for letter in &step.letters {
                // The moved source, its absolute bound, and the stack beside the running factor.
                let moved_rows = match letter {
                    ObservabilityLetter::Linear(_) => source_rows,
                    ObservabilityLetter::Units { reads, .. } => reads.nrows() + source_rows,
                    ObservabilityLetter::RoutingLaws(letters) => letters.transports().len().max(1) * source_rows,
                };
                let letter_reservation = reserve(
                    governor,
                    moved_rows.max(1) + input,
                    input.max(width),
                    3,
                    "weighted observability: letter",
                )?;
                let (moved, moved_formation) = letter.pull(&source, &absolute_source, formation);
                let mut stack = Array2::<f64>::zeros((pulled.nrows() + moved.nrows(), input));
                stack.slice_mut(s![..pulled.nrows(), ..]).assign(&pulled);
                stack.slice_mut(s![pulled.nrows().., ..]).assign(&moved);
                let stack_formation = pulled_formation.hypot(moved_formation);
                let compressed = compress_factor(governor, &stack, "weighted observability: compression")?;
                pulled = compressed.factor;
                pulled_directions = compressed.directions;
                pulled_sigma = compressed.singular_values;
                pulled_formation = stack_formation + compressed.formation;
                drop(letter_reservation);
            }
            drop(source_reservation);
            stacked_rows = stacked_rows
                .saturating_add(readout_rows)
                .saturating_mul(step.letters.iter().map(ObservabilityLetter::count).sum());
            step_spectra.push(ObservabilitySpectrum::of(
                pulled_sigma,
                pulled.nrows(),
                input,
                pulled_formation,
                stacked_rows,
            ));
            factor = pulled;
            directions = pulled_directions;
            formation = pulled_formation;
            width = input;
        }
        step_spectra.reverse();
        Ok(Self {
            factor,
            directions,
            formation,
            step_spectra,
        })
    }

    /// The spectrum of `G` at `h_0`.
    pub fn spectrum(&self) -> &ObservabilitySpectrum {
        &self.step_spectra[0]
    }

    /// How much of `G` a declared candidate subspace holds (the row span of
    /// `candidate`, `k × n_0`, of full row rank `k`), and its principal angles
    /// to the top `k` Gramian directions. The candidate is the caller's
    /// declaration; nothing here chooses one.
    pub fn capture(
        &self,
        governor: &MemoryGovernor,
        candidate: ArrayView2<'_, f64>,
    ) -> Result<SubspaceCapture, StateError> {
        let width = self.factor.ncols();
        require_sample(candidate, width, "weighted observability: candidate")?;
        let declared = candidate.nrows();
        let basis = resolved_row_space(
            governor,
            &candidate.to_owned(),
            0.0,
            "weighted observability: candidate",
        )?;
        if basis.rank != declared {
            return Err(StateError::CandidateRankDeficient {
                declared,
                resolved: basis.rank,
            });
        }
        let orthonormal = basis.rows;
        // The projection, its absolute bound, and the directions' overlap.
        let working = reserve(
            governor,
            declared.max(self.factor.nrows()).max(1),
            width.max(declared),
            3,
            "weighted observability: capture",
        )?;
        let orthonormality = orthonormality_defect(&orthonormal);
        let projected = self.factor.dot(&orthonormal.t());
        let projected_band = entrywise_band_norm(
            self.factor
                .mapv(f64::abs)
                .dot(&orthonormal.t().mapv(f64::abs))
                .mapv(|magnitude| accumulation_band(width, magnitude)),
        );
        let total = frobenius(&self.factor);
        let held = frobenius(&projected);
        let held_error = self.formation * (1.0 + orthonormality)
            + projected_band
            + total * orthonormality
            + accumulation_growth(projected.len().max(1)) * held;
        let total_error = self.formation + accumulation_growth(self.factor.len().max(1)) * total;
        let fraction = if total > 0.0 { (held / total).powi(2) } else { 0.0 };
        let lower = if total > 0.0 {
            ((held - held_error).max(0.0) / (total + total_error)).powi(2)
        } else {
            0.0
        };
        let upper = if total > total_error {
            ((held + held_error) / (total - total_error)).powi(2).min(1.0)
        } else {
            1.0
        };
        let numerical_error = (fraction - lower).max(upper - fraction).max(0.0);
        let energy_fraction = EvidenceStatus::exact(
            fraction,
            numerical_error,
            ExactBasis::Algebraic,
            None,
            StateDomain::UnitStates { dimension: width },
        )
        .map_err(|source| StateError::Evidence { source })?;

        let top = declared.min(self.directions.nrows());
        let mut principal_cosines = if top == 0 {
            Vec::new()
        } else {
            let overlap = self.directions.slice(s![..top, ..]).dot(&orthonormal.t());
            let (_, cosines, _) = overlap.svd(false, false).map_err(|source| StateError::Svd {
                context: "weighted observability: principal angles",
                source,
            })?;
            cosines.to_vec()
        };
        principal_cosines.sort_by(|left, right| right.total_cmp(left));
        drop(working);

        let sigma = &self.spectrum().singular_values;
        let at = |index: usize| sigma.get(index).copied().unwrap_or(0.0);
        let eigengap = at(declared - 1).powi(2) - at(declared).powi(2);
        let error = self.formation + factor_singular_band(self.factor.nrows().max(1), width, at(0));
        let perturbation = 2.0 * at(0) * error + error * error;
        let angle_perturbation = if eigengap > perturbation {
            (perturbation / (eigengap - perturbation)).min(1.0)
        } else {
            1.0
        };
        Ok(SubspaceCapture {
            dimension: declared,
            energy_fraction,
            principal_cosines,
            eigengap,
            angle_perturbation,
        })
    }
}

/// A stack compressed to `diag(σ) Vᵀ`, with `σ` in decreasing order, `V`'s rows,
/// and the compression's own Frobenius formation bound.
struct CompressedFactor {
    factor: Array2<f64>,
    directions: Array2<f64>,
    singular_values: Vec<f64>,
    formation: f64,
}

fn compress_factor(
    governor: &MemoryGovernor,
    stack: &Array2<f64>,
    context: &'static str,
) -> Result<CompressedFactor, StateError> {
    let (rows, cols) = stack.dim();
    if rows == 0 {
        return Ok(CompressedFactor {
            factor: Array2::zeros((0, cols)),
            directions: Array2::zeros((0, cols)),
            singular_values: Vec::new(),
            formation: 0.0,
        });
    }
    // The decomposition's working copy, then `Vᵀ`, the directions and the factor.
    let working = reserve(governor, rows, cols, 1, context)?;
    let factors = reserve(governor, cols, cols, 3, context)?;
    let (_, sigma, vt) = stack
        .svd(false, true)
        .map_err(|source| StateError::Svd { context, source })?;
    let vt = vt.ok_or(StateError::Svd {
        context,
        source: FaerLinalgError::SvdNoConvergence { context },
    })?;
    let mut order: Vec<usize> = (0..sigma.len()).collect();
    order.sort_by(|&left, &right| sigma[right].total_cmp(&sigma[left]));
    let kept = order.len();
    let mut directions = Array2::<f64>::zeros((kept, cols));
    let mut factor = Array2::<f64>::zeros((kept, cols));
    let mut singular_values = Vec::with_capacity(kept);
    for (row, &index) in order.iter().enumerate() {
        directions.row_mut(row).assign(&vt.row(index));
        factor
            .row_mut(row)
            .assign(&vt.row(index).mapv(|value| value * sigma[index]));
        singular_values.push(sigma[index]);
    }
    let sigma_max = singular_values.first().copied().unwrap_or(0.0);
    let sigma_norm = singular_values.iter().map(|value| value * value).sum::<f64>().sqrt();
    let formation = (kept as f64).sqrt() * factor_singular_band(rows, cols, sigma_max)
        + sigma_max * orthonormality_defect(&directions)
        + accumulation_growth(1) * sigma_norm;
    drop(working);
    drop(factors);
    Ok(CompressedFactor {
        factor,
        directions,
        singular_values,
        formation,
    })
}

/// `‖W Wᵀ − I‖_F` plus the rounding of the product: a bound on the distance of
/// the rows of `W` from an exactly orthonormal set.
pub(super) fn orthonormality_defect(rows: &Array2<f64>) -> f64 {
    let count = rows.nrows();
    let width = rows.ncols();
    let gram = rows.dot(&rows.t()) - Array2::<f64>::eye(count);
    let absolute = rows.mapv(f64::abs);
    let band = entrywise_band_norm(
        absolute
            .dot(&absolute.t())
            .mapv(|magnitude| accumulation_band(width + 1, magnitude + 1.0)),
    );
    frobenius(&gram) + band
}

pub(super) fn frobenius<S: ndarray::Data<Elem = f64>>(matrix: &ndarray::ArrayBase<S, ndarray::Ix2>) -> f64 {
    matrix.iter().map(|value| value * value).sum::<f64>().sqrt()
}

/// The resolved row space of a matrix: its singular values, the band, the rank
/// and the leading right singular vectors as rows.
pub(super) struct ResolvedRowSpace {
    pub(super) singular_values: Vec<f64>,
    pub(super) band: f64,
    pub(super) rank: usize,
    pub(super) rows: Array2<f64>,
}

pub(super) fn resolved_row_space(
    governor: &MemoryGovernor,
    matrix: &Array2<f64>,
    formation: f64,
    context: &'static str,
) -> Result<ResolvedRowSpace, StateError> {
    let (rows, cols) = matrix.dim();
    // The decomposition's working copy, then `Vᵀ` and the resolved rows beside it.
    let working = reserve(governor, rows, cols, 1, context)?;
    let factors = reserve(governor, cols, cols, 2, context)?;
    let (_, sigma, vt) = matrix
        .svd(false, true)
        .map_err(|source| StateError::Svd { context, source })?;
    let vt = vt.ok_or(StateError::Svd {
        context,
        source: FaerLinalgError::SvdNoConvergence { context },
    })?;
    let mut order: Vec<usize> = (0..sigma.len()).collect();
    order.sort_by(|&left, &right| sigma[right].total_cmp(&sigma[left]));
    let singular_values: Vec<f64> = order.iter().map(|&index| sigma[index]).collect();
    let sigma_max = singular_values.first().copied().unwrap_or(0.0);
    let band = factor_singular_band(rows, cols, sigma_max) + formation;
    let rank = singular_values.iter().filter(|&&value| value > band).count();
    let mut resolved = Array2::<f64>::zeros((rank, cols));
    for (row, &index) in order.iter().take(rank).enumerate() {
        resolved.row_mut(row).assign(&vt.row(index));
    }
    drop(working);
    drop(factors);
    Ok(ResolvedRowSpace {
        singular_values,
        band,
        rank,
        rows: resolved,
    })
}

pub(super) fn spectral_norm_bounds(
    governor: &MemoryGovernor,
    matrix: &Array2<f64>,
    formation: f64,
    context: &'static str,
) -> Result<SpectralNormBounds, StateError> {
    if matrix.is_empty() {
        return Ok(SpectralNormBounds {
            lower: 0.0,
            upper: formation,
        });
    }
    let (rows, cols) = matrix.dim();
    // The decomposition's working copy.
    let working = reserve(governor, rows, cols, 1, context)?;
    let (_, sigma, _) = matrix
        .svd(false, false)
        .map_err(|source| StateError::Svd { context, source })?;
    drop(working);
    let sigma_max = sigma.iter().fold(0.0_f64, |largest, &value| largest.max(value));
    let band = factor_singular_band(rows, cols, sigma_max) + formation;
    Ok(SpectralNormBounds {
        lower: (sigma_max - band).max(0.0),
        upper: sigma_max + band,
    })
}

/// Reserves `copies` dense `rows × cols` matrices on `governor` before they are formed.
pub(super) fn reserve(
    governor: &MemoryGovernor,
    rows: usize,
    cols: usize,
    copies: usize,
    context: &'static str,
) -> Result<MemoryReservation, StateError> {
    governor
        .try_reserve_dense_f64_copies(rows, cols, copies, context)
        .map_err(|source| StateError::Memory { context, source })
}

/// `‖B‖_F` of an entrywise error bound `B`, which bounds the spectral norm of the
/// error.
pub(super) fn entrywise_band_norm(band: Array2<f64>) -> f64 {
    band.iter().map(|entry| entry * entry).sum::<f64>().sqrt()
}

fn linear_family_dimension(
    readouts: &[ArrayView2<'_, f64>],
    transitions: &[ArrayView2<'_, f64>],
) -> Result<usize, StateError> {
    let dimension = readouts
        .first()
        .ok_or(StateError::EmptyFamily {
            context: "linear quotient: readouts",
        })?
        .ncols();
    for readout in readouts {
        require_sample(readout.view(), dimension, "linear quotient: readout")?;
    }
    for transition in transitions {
        require_dimension(transition.nrows(), dimension, "linear quotient: transition rows")?;
        require_sample(transition.view(), dimension, "linear quotient: transition")?;
    }
    Ok(dimension)
}

/// Errors and refusals of the sufficient-state checks.
#[derive(Debug)]
pub enum StateError {
    /// No futures, responses, states or codes were stated.
    EmptyFamily { context: &'static str },
    /// Two dimensions that must agree do not.
    DimensionMismatch {
        context: &'static str,
        expected: usize,
        found: usize,
    },
    /// A stated sample, value, Jacobian or roundoff bound is not finite.
    NonFinite { context: &'static str },
    /// A bound that must be non-negative is negative.
    NegativeBound { context: &'static str, value: f64 },
    /// The declared fidelity tolerance is negative or not finite.
    InvalidFidelity { value: f64 },
    /// A native map could not execute.
    Execution { reason: String },
    /// `E(D(E h))` differs from `E(h)` by more than the arithmetic explains, so
    /// the decoder is not a section of the encoder at this state's code.
    NotASection {
        state: usize,
        code_defect: f64,
        roundoff: f64,
    },
    /// Every stated state lies on the chart's section within the decoder's
    /// roundoff, so each comparison was of a state with itself and no fibre was
    /// tested.
    VacuousFiberTest { states: usize },
    /// A singular value decomposition failed.
    Svd {
        context: &'static str,
        source: FaerLinalgError,
    },
    /// An evaluated defect could not be expressed as an evidence status.
    Evidence { source: EvidenceStatusError },
    /// A dense matrix the check forms does not fit the memory budget.
    Memory {
        context: &'static str,
        source: MemoryReservationError,
    },
    /// A declared candidate subspace's rows do not resolve to full row rank.
    CandidateRankDeficient { declared: usize, resolved: usize },
}

impl fmt::Display for StateError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::EmptyFamily { context } => write!(formatter, "{context}: nothing was stated"),
            Self::DimensionMismatch {
                context,
                expected,
                found,
            } => write!(formatter, "{context}: expected dimension {expected}, found {found}"),
            Self::NonFinite { context } => write!(formatter, "{context}: non-finite value"),
            Self::NegativeBound { context, value } => {
                write!(formatter, "{context}: bound {value} is negative")
            }
            Self::InvalidFidelity { value } => write!(
                formatter,
                "declared fidelity tolerance {value} is not a finite non-negative number"
            ),
            Self::Execution { reason } => write!(formatter, "native map failed: {reason}"),
            Self::NotASection {
                state,
                code_defect,
                roundoff,
            } => write!(
                formatter,
                "fiber test: at state {state} the decoder is not a section: E(D(E h)) differs \
                 from E(h) by {code_defect:e}, above the roundoff bound {roundoff:e}"
            ),
            Self::VacuousFiberTest { states } => write!(
                formatter,
                "fiber test: all {states} states lie on the chart's section, so no fibre was tested"
            ),
            Self::Svd { context, source } => {
                write!(formatter, "{context}: singular value decomposition failed: {source}")
            }
            Self::Evidence { source } => {
                write!(formatter, "evidence status refused an evaluated defect: {source}")
            }
            Self::Memory { context, source } => write!(formatter, "{context}: {source}"),
            Self::CandidateRankDeficient { declared, resolved } => write!(
                formatter,
                "declared candidate subspace has {declared} rows but resolves to rank {resolved}"
            ),
        }
    }
}

impl std::error::Error for StateError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Svd { source, .. } => Some(source),
            Self::Evidence { source } => Some(source),
            Self::Memory { source, .. } => Some(source),
            _ => None,
        }
    }
}

/// The stated item whose certified defect is largest, the uniform bound over all
/// stated items, the largest combined roundoff, and the number of items.
struct DefectRecord {
    violation: Option<(usize, f64, f64, EvidenceStatus<(), ()>)>,
    bound: f64,
    roundoff: f64,
    count: usize,
}

impl DefectRecord {
    fn new() -> Self {
        Self {
            violation: None,
            bound: 0.0,
            roundoff: 0.0,
            count: 0,
        }
    }

    fn observe(&mut self, index: usize, defect: f64, roundoff: f64) -> Result<(), StateError> {
        let item = evaluated_defect(defect, roundoff)?;
        self.count += 1;
        self.bound = self.bound.max(certified_upper(&item));
        self.roundoff = self.roundoff.max(roundoff);
        if item.refutes_at_most(0.0) {
            let larger = match &self.violation {
                Some((_, _, _, worst)) => certified_lower(&item) > certified_lower(worst),
                None => true,
            };
            if larger {
                self.violation = Some((index, defect, roundoff, item));
            }
        }
        Ok(())
    }
}

/// One evaluated defect with its combined roundoff, as the status supports.rs
/// owns: exact up to numerical error over the single evaluated item. Verdicts
/// read its rounded bounds and threshold predicates, the derivation
/// [`EvidenceStatus::counterexample`] reads, so no copy of that arithmetic lives
/// here.
fn evaluated_defect(value: f64, roundoff: f64) -> Result<EvidenceStatus<(), ()>, StateError> {
    EvidenceStatus::exact(
        value,
        roundoff,
        ExactBasis::Exhaustive { cardinality: 1 },
        None,
        (),
    )
    .map_err(|source| StateError::Evidence { source })
}

/// The item's certified lower bound. An exact status always has one.
fn certified_lower(item: &EvidenceStatus<(), ()>) -> f64 {
    item.lower_bound().unwrap_or(f64::NEG_INFINITY)
}

/// The item's certified upper bound. An exact status always has one.
fn certified_upper(item: &EvidenceStatus<(), ()>) -> f64 {
    item.upper_bound().unwrap_or(f64::INFINITY)
}

fn evaluated<M: NativeMap + ?Sized>(
    map: &M,
    input: ArrayView1<'_, f64>,
    input_roundoff: f64,
    context: &'static str,
) -> Result<Evaluation, StateError> {
    require_dimension(input.len(), map.input_dimension(), context)?;
    let evaluation = map.evaluate(input, input_roundoff)?;
    require_dimension(evaluation.value.len(), map.output_dimension(), context)?;
    if !evaluation.roundoff.is_finite()
        || evaluation.roundoff < 0.0
        || evaluation.value.iter().any(|value| !value.is_finite())
    {
        return Err(StateError::NonFinite { context });
    }
    Ok(evaluation)
}

fn require_dimension(found: usize, expected: usize, context: &'static str) -> Result<(), StateError> {
    if found == expected {
        Ok(())
    } else {
        Err(StateError::DimensionMismatch {
            context,
            expected,
            found,
        })
    }
}

fn require_finite(matrix: ArrayView2<'_, f64>, context: &'static str) -> Result<(), StateError> {
    if matrix.iter().all(|value| value.is_finite()) {
        Ok(())
    } else {
        Err(StateError::NonFinite { context })
    }
}

fn require_sample(
    sample: ArrayView2<'_, f64>,
    dimension: usize,
    context: &'static str,
) -> Result<(), StateError> {
    if sample.nrows() == 0 {
        return Err(StateError::EmptyFamily { context });
    }
    require_dimension(sample.ncols(), dimension, context)?;
    if sample.iter().any(|value| !value.is_finite()) {
        return Err(StateError::NonFinite { context });
    }
    Ok(())
}

fn sup_distance(left: ArrayView1<'_, f64>, right: ArrayView1<'_, f64>) -> f64 {
    left.iter()
        .zip(right.iter())
        .fold(0.0_f64, |largest, (a, b)| largest.max((a - b).abs()))
}

